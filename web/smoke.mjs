import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.FLYWORLD_URL||'http://127.0.0.1:5173/');
await page.waitForFunction(()=>window.flyworld,{timeout:60000});
await page.waitForTimeout(1200);
assert.equal(await page.locator('#error').isVisible(),false);
assert.ok((await page.evaluate(()=>window.flyworld.snapshot())).memory);
await page.screenshot({path:'test-results/desktop.png'});
await page.locator('#learning').uncheck();
const before=await page.evaluate(()=>window.flyworld.snapshot());
await page.waitForTimeout(800);
assert.equal((await page.evaluate(()=>window.flyworld.snapshot())).updates,before.updates);
await page.locator('#pause').click();
const paused=await page.evaluate(()=>window.flyworld.snapshot());await page.waitForTimeout(400);
assert.equal((await page.evaluate(()=>window.flyworld.snapshot())).time,paused.time);
await page.locator('#pause').click();
await page.locator('[data-action="feed"]').click();
await page.locator('#replay-mode').click();
await page.waitForFunction(()=>window.flyworld.snapshot().recordedSpikes>0);
assert.equal(await page.locator('#recording option').count(),6);
assert.equal((await page.evaluate(()=>window.flyworld.snapshot())).neuralLive,false);
await page.screenshot({path:'test-results/replay.png'});
await page.locator('#free-mode').click();
await page.locator('#help').click();assert.ok(await page.locator('#help-dialog').isVisible());await page.locator('#close-help').click();
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(300);await page.screenshot({path:'test-results/mobile.png'});
await page.locator('#panel-toggle').click();assert.ok(await page.locator('#monitor').isVisible());
assert.deepEqual(errors,[]);console.log(JSON.stringify({url:page.url(),snapshot:await page.evaluate(()=>window.flyworld.snapshot()),errors}));
await browser.close();
