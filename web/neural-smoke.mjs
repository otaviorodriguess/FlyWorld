import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1280,height:900},deviceScaleFactor:.35});
 await page.addInitScript(()=>{const raf=requestAnimationFrame.bind(window);window.requestAnimationFrame=cb=>raf(()=>setTimeout(()=>cb(performance.now()),120));});
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:8765');
 await page.waitForFunction(()=>window.flyworld?.snapshot().neural.frame?.experiment==='sugar',{},{timeout:180000});
 const initial=await page.evaluate(()=>window.flyworld.snapshot());
 assert.equal(initial.mode,'neural');assert.equal(initial.neural.population,138639);
 assert.equal(initial.neural.frame.command[0],0);
 await page.keyboard.down('ArrowUp');await page.keyboard.down('ArrowRight');
 await page.waitForTimeout(1200);await page.keyboard.up('ArrowUp');await page.keyboard.up('ArrowRight');
 const unmoved=await page.evaluate(()=>window.flyworld.snapshot());
 assert.deepEqual(unmoved.position,initial.position);assert.equal(unmoved.updates,initial.updates);
 assert.equal(await page.locator('#lan-mode').isDisabled(),true);
 await page.locator('#neural-food').click();
 await page.waitForFunction(()=>window.flyworld.snapshot().neural.frame?.stimulus>0,{},{timeout:180000});
 await page.waitForFunction(()=>window.flyworld.snapshot().neural.frame?.spikes>0,{},{timeout:180000});
 const sensory=await page.evaluate(()=>window.flyworld.snapshot());
 assert.equal(sensory.neural.frame.command[0],0);
 await page.locator('#neural-protocol').scrollIntoViewIfNeeded();await page.locator('#neural-protocol').selectOption('p9');
 await page.waitForFunction(()=>{const s=window.flyworld.snapshot();return s.neural.frame?.experiment==='p9'&&s.neural.frame.command[0]>0&&Math.hypot(s.position.x-3000,s.position.z-2000)>0;},{},{timeout:180000});
 const motor=await page.evaluate(()=>window.flyworld.snapshot());
 assert.equal(motor.updates,initial.updates);
 await page.locator('#pause').click();
 const paused=await page.evaluate(()=>window.flyworld.snapshot());
 await page.waitForTimeout(3500);
 assert.deepEqual((await page.evaluate(()=>window.flyworld.snapshot())).position,paused.position);
 await page.locator('#pause').click();
 await page.route('**/api/neural/poll',route=>route.abort());
 await page.waitForFunction(()=>window.flyworld.snapshot().neural.state==='error',{},{timeout:180000});
 const disconnected=await page.evaluate(()=>window.flyworld.snapshot());
 await page.waitForTimeout(1600);
 assert.deepEqual((await page.evaluate(()=>window.flyworld.snapshot())).position,disconnected.position);
 assert.equal(disconnected.neuralLive,false);
 await page.unroute('**/api/neural/poll');
 await page.locator('#free-mode').click();
 await page.waitForFunction(()=>window.flyworld.snapshot().mode==='free');
 await page.locator('#lan-mode').click();
 assert.equal((await page.evaluate(()=>window.flyworld.snapshot())).location,'lanhouse');
 await page.locator('#return-garden').click();
 await page.locator('#neural-mode').click();
 await page.waitForFunction(()=>window.flyworld.snapshot().neural.population===138639);
 await page.locator('#pause').click();
 await mkdir('test-results',{recursive:true});
 await page.screenshot({path:'test-results/neural-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.locator('#panel-toggle').click();
 await page.screenshot({path:'test-results/neural-mobile.png'});
 assert.deepEqual(errors,[]);
 const report={population:initial.neural.population,sensory:sensory.neural.frame,motor:motor.neural.frame,motorPosition:motor.position,manualIgnored:true,qUnchanged:true,pauseFreezesBody:true,connectionFailureFreezesBody:true,errors};
 await writeFile('test-results/neural-browser.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
}finally{await browser.close();}
